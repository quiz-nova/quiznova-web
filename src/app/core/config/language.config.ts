export const RTL_LANGUAGES = ['ar', 'fa', 'he', 'ur'];

export function isRtlLanguage(langCode: string | null | undefined): boolean {
  if (!langCode) {
    return false;
  }
  return RTL_LANGUAGES.includes(langCode.toLowerCase());
}

